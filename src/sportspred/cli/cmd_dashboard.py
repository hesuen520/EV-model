"""Dashboard and report commands."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

import click

from . import Context, pass_ctx


def write_validation_docs(store, out_dir: Path) -> Path:
    """Markdown summary of every recorded real validation run, with charts."""
    from ..dashboard import validation_views
    from ..validation.plots import improvement_svg, reliability_svg, standalone

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "charts").mkdir(exist_ok=True)
    reports = sorted(validation_views(store), key=lambda r: (r["sport"], r["league"], r["market"]))
    lines = [
        "# Validation results", "",
        "Generated by `sportspred report validation` from the validation runs recorded in the store. Every number "
        "comes from a run that was actually executed; nothing is typed in by hand.", "",
        "Protocol for every league and market: chronological walk-forward folds; calibration fitted on a block "
        "between training and test; model selection on pooled development-fold log loss with a one-standard-error "
        "preference for the simpler candidate; the final test period read once, after selection; intervals from a "
        "bootstrap that resamples whole slates. Accuracy, calibration and price-dependent value are separate "
        "questions - nothing here says a model beats a market.", "",
        "## Summary", "",
        "| Sport | League | Market | Status | Selected model | Final-test period | n | Accuracy (95% interval) | "
        "Log loss (95% interval) | Base-rate log loss | Calibration error | Market benchmark log loss |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in reports:
        s, f = r["final_test"]["selected"], r["final_test"]
        base = (f.get("baselines") or {}).get("base_rate", {})
        bench = r.get("market_benchmark")
        status = "validated" if r.get("gates_passed") else "experimental"
        lines.append(
            f"| {r['sport']} | `{r['league']}` | {r['market']} | **{status}** | {r['selected_model']} | "
            f"{s['first_event'][:10]} to {s['last_event'][:10]} | {s['n']} | {100 * s['accuracy']:.1f}% "
            f"({100 * s['accuracy_ci'][0]:.1f}-{100 * s['accuracy_ci'][1]:.1f}) | {s['log_loss']:.4f} "
            f"({s['log_loss_ci'][0]:.4f}-{s['log_loss_ci'][1]:.4f}) | "
            f"{base.get('log_loss', float('nan')):.4f} | {s['ece']:.4f} | "
            f"{'' if not bench else format(bench['market']['log_loss'], '.4f') + ' (model ' + format(bench['model_same_events']['log_loss'], '.4f') + ' on the same ' + str(bench['n']) + ' events)'} |")
    for r in reports:
        s, f, d = r["final_test"]["selected"], r["final_test"], r["dev"]
        key = f"{r['league']}_{r['market']}"
        rel = f.get("reliability_selected_outcome", [])
        (out_dir / "charts" / f"{key}_calibration.svg").write_text(
            standalone(reliability_svg(rel, title=f"{r['league']} {r['market']}: calibration of selections (final test)")))
        stab = d.get("stability_vs_baselines") or {}
        ref = next((k for k in stab if k != "base_rate"), next(iter(stab), None))
        lines += ["", f"## {r['league']} - {r['market']}", "",
                  f"{r['data']['n_completed']} completed events from {r['data']['first_event'][:10]} to "
                  f"{r['data']['last_event'][:10]}; {len(r['protocol']['dev_folds'])} walk-forward folds; final test "
                  f"blocks {', '.join(f['blocks'])}. Selected: `{r['selected_model']}` ({r['selection_note']}).", "",
                  f"![calibration](charts/{key}_calibration.svg)"]
        if ref:
            (out_dir / "charts" / f"{key}_by_season.svg").write_text(standalone(improvement_svg(
                stab[ref]["by_block"], reference=ref,
                title=f"{r['league']} {r['market']}: log-loss improvement over {ref} by season (development)")))
            lines += [f"![by season](charts/{key}_by_season.svg)", "",
                      f"Season by season on development folds the selected model beat `{ref}` in "
                      f"{stab[ref]['blocks_improved']} of {stab[ref]['blocks']} seasons."]
        lines += ["", "| Model | Development n | Dev accuracy | Dev log loss | Dev Brier |", "|---|---|---|---|---|"]
        for c in r["candidates"]:
            tag = " (selected)" if c["name"] == r["selected_model"] else (" [retrospective]" if c["uses_retrospective"] else "")
            lines.append(f"| {c['name']}{tag} | {c['dev']['n']} | {100 * c['dev']['accuracy']:.1f}% | "
                         f"{c['dev']['log_loss']:.4f} | {c['dev']['brier']:.4f} |")
        lines += ["", "Final test:", "", "| Model | n | Accuracy | Log loss | Brier |", "|---|---|---|---|---|",
                  f"| {r['selected_model']} (selected) | {s['n']} | {100 * s['accuracy']:.1f}% | {s['log_loss']:.4f} | {s['brier']:.4f} |"]
        for n, m in (f.get("baselines") or {}).items():
            lines.append(f"| baseline {n} | {m['n']} | {100 * m['accuracy']:.1f}% | {m['log_loss']:.4f} | {m['brier']:.4f} |")
        for n, m in (f.get("retrospective_experiments") or {}).items():
            lines.append(f"| retrospective upper bound {n} (not a realistic backtest) | {m['n']} | "
                         f"{100 * m['accuracy']:.1f}% | {m['log_loss']:.4f} | {m['brier']:.4f} |")
        bench = r.get("market_benchmark")
        if bench:
            lines.append(f"| market benchmark: {bench['label']} ({bench['timing']}) | {bench['n']} | "
                         f"{100 * bench['market']['accuracy']:.1f}% | {bench['market']['log_loss']:.4f} | "
                         f"{bench['market']['brier']:.4f} |")
        lines += ["", "After the PASS rule (final test):", "",
                  "| Minimum probability | Selections | Coverage | Accuracy (95% interval) | Mean predicted |", "|---|---|---|---|---|"]
        for p in f.get("pass_rule", []):
            if p.get("n_selected"):
                lines.append(f"| {p['min_prob']:.2f} | {p['n_selected']} | {100 * p['coverage']:.1f}% | "
                             f"{100 * p['accuracy']:.1f}% ({100 * p['accuracy_low']:.1f}-{100 * p['accuracy_high']:.1f}) | "
                             f"{100 * p['mean_predicted']:.1f}% |")
        corr = r.get("same_day_residual_correlation") or {}
        if corr.get("rho") is not None:
            lines += ["", f"Same-slate residual correlation (used by the combo builder): {corr['rho']:+.4f} "
                          f"(95% interval {corr['low']:+.4f} to {corr['high']:+.4f}, {corr['n_pairs']} event pairs)."]
        lines += ["", "Gates:", ""] + [f"- {'passed' if g['passed'] else 'NOT met'} - {g['gate'].replace('_', ' ')}: {g['detail']}"
                                       for g in r["gates"]]
        if r.get("limitations"):
            lines += ["", "Limitations:", ""] + [f"- {x}" for x in r["limitations"]]
    path = out_dir / "VALIDATION.md"
    path.write_text("\n".join(lines) + "\n")
    return path


def register(main: click.Group) -> None:
    @main.command()
    @click.option("--out", "out", default=None, type=click.Path(dir_okay=False),
                  help="Where to write the page (default: <data dir>/reports/dashboard.html).")
    @click.option("--include-synthetic", is_flag=True, help="Show synthetic demo content (banner-labelled).")
    @pass_ctx
    def dashboard(ctx: Context, out: Optional[str], include_synthetic: bool) -> None:
        """Write the self-contained HTML dashboard (open it in any browser)."""
        from ..dashboard import build_dashboard

        path = Path(out) if out else ctx.settings.paths.reports / "dashboard.html"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(build_dashboard(ctx.store, ctx.settings, include_synthetic=include_synthetic), encoding="utf-8")
        click.echo(f"wrote {path} ({path.stat().st_size // 1024} KB). Open it in a browser; it needs no server.")

    @main.group()
    def report() -> None:
        """Write reports from recorded runs."""

    @report.command("validation")
    @click.option("--out", "out", default="docs/validation", show_default=True, type=click.Path(file_okay=False))
    @pass_ctx
    def report_validation(ctx: Context, out: str) -> None:
        """Markdown validation results with calibration and season charts."""
        click.echo(f"wrote {write_validation_docs(ctx.store, Path(out))}")
